async def main():
    from sqlalchemy import select, text
    from app.core.database import AsyncSessionLocal
    from app.models.city import City

    print(f"\nSeeding {len(CITIES)} cities...")
    async with AsyncSessionLocal() as session:
        seeded, skipped = 0, 0
        for c in CITIES:
            # Check if already exists
            result = await session.execute(select(City).where(City.name == c["name"]))
            existing = result.scalar_one_or_none()
            if existing:
                print(f"  ~ {c['name']} already exists — skipping")
                skipped += 1
                continue

            city = City(**c)
            session.add(city)
            print(f"  + {c['name']} (Tier {c['tier']}, {c['state']})")
            seeded += 1

        await session.commit()

    print(f"\n{'='*55}")
    print(f"  DONE — {seeded} cities seeded, {skipped} skipped")
    print(f"{'='*55}\n")


asyncio.run(main())
